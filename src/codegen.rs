//! Generate small, runnable Java programs that reproduce common thread problems.
//!
//! feat-007: given a scenario, emit Java source whose thread dump exhibits the
//! matching problem pattern that this tool analyzes:
//!
//! - [`Scenario::LockContention`] — many threads block waiting to enter one
//!   monitor while a single thread holds it (RUNNABLE holder + BLOCKED waiters).
//! - [`Scenario::Deadlock`] — `n` threads form a circular wait: each holds one
//!   lock and blocks trying to acquire the next, closing a deadlock cycle.
//!
//! This module is plain Rust (no `wasm-bindgen`) so it is host-testable.

use serde::Serialize;

/// A reproducible thread-problem scenario.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum Scenario {
    /// One holder + N-1 threads blocked waiting to lock the same monitor.
    LockContention,
    /// N threads in a circular wait (classic deadlock cycle).
    Deadlock,
}

impl Scenario {
    /// The generated Java public class name (also the file name stem).
    pub fn class_name(self) -> &'static str {
        match self {
            Scenario::LockContention => "LockContention",
            Scenario::Deadlock => "DeadlockCycle",
        }
    }
}

/// Parse a scenario name coming from the UI/JS layer. Accepts a few aliases.
pub fn parse_scenario(name: &str) -> Option<Scenario> {
    match name.trim().to_ascii_lowercase().replace('_', "-").as_str() {
        "lock-contention" | "contention" | "waiting" | "waiting-threads" => {
            Some(Scenario::LockContention)
        }
        "deadlock" | "deadlock-cycle" | "cycle" => Some(Scenario::Deadlock),
        _ => None,
    }
}

/// Clamp the requested thread/worker count into a sane range (>= 2).
fn normalize_count(count: usize) -> usize {
    count.clamp(2, 64)
}

/// Generate Java source for the given scenario and thread count.
pub fn generate(scenario: Scenario, count: usize) -> String {
    let n = normalize_count(count);
    match scenario {
        Scenario::LockContention => generate_lock_contention(n),
        Scenario::Deadlock => generate_deadlock(n),
    }
}

fn generate_lock_contention(workers: usize) -> String {
    format!(
        r#"// Auto-generated by jblock (feat-007): lock-contention reproducer.
// One thread holds LOCK forever; the other {n_minus_1} block waiting to enter it.
// Capture with: jstack <pid>  (or ThreadMXBean#dumpAllThreads)
public class LockContention {{
    private static final Object LOCK = new Object();

    public static void main(String[] args) {{
        final int workers = {workers};
        for (int i = 0; i < workers; i++) {{
            final int id = i;
            Thread t = new Thread(() -> {{
                synchronized (LOCK) {{
                    System.out.println("worker-" + id + " acquired LOCK");
                    // Hold the monitor so the remaining workers stay BLOCKED.
                    while (true) {{
                        try {{
                            Thread.sleep(Long.MAX_VALUE);
                        }} catch (InterruptedException e) {{
                            Thread.currentThread().interrupt();
                            return;
                        }}
                    }}
                }}
            }}, "worker-" + i);
            t.start();
        }}
    }}
}}
"#,
        workers = workers,
        n_minus_1 = workers - 1
    )
}

fn generate_deadlock(threads: usize) -> String {
    format!(
        r#"// Auto-generated by jblock (feat-007): deadlock-cycle reproducer.
// {n} threads and {n} locks form a circular wait: thread i holds lock i and
// blocks acquiring lock (i+1) % {n}, closing a deadlock cycle.
// Capture with: jstack <pid>  (jstack also prints "Found one Java-level deadlock").
public class DeadlockCycle {{
    public static void main(String[] args) {{
        final int n = {threads};
        final Object[] locks = new Object[n];
        for (int i = 0; i < n; i++) {{
            locks[i] = new Object();
        }}
        for (int i = 0; i < n; i++) {{
            final int id = i;
            final Object first = locks[i];
            final Object second = locks[(i + 1) % n];
            Thread t = new Thread(() -> {{
                synchronized (first) {{
                    System.out.println("thread-" + id + " locked " + id);
                    try {{
                        Thread.sleep(200);
                    }} catch (InterruptedException e) {{
                        Thread.currentThread().interrupt();
                        return;
                    }}
                    synchronized (second) {{
                        System.out.println("thread-" + id + " locked next");
                    }}
                }}
            }}, "deadlock-" + i);
            t.start();
        }}
    }}
}}
"#,
        threads = threads,
        n = threads
    )
}

