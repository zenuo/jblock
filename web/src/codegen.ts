/**
 * Generate a runnable Java reproducer for a thread problem scenario.
 * Port of the former Rust/WASM `generateJava` (moved in feat-011 to shrink WASM).
 */
export function generateJava(scenario: JavaScenario, count: number): string {
  const n = normalizeCount(count);
  switch (scenario) {
    case "deadlock":
      return generateDeadlock(n);
    case "thread-pool-exhaustion":
      return generateThreadPoolExhaustion(n);
    case "sync-io-hotspot":
      return generateSyncIoHotspot(n);
    case "dangerous-hot-lock":
      return generateDangerousHotLock(n);
    case "connection-pool-starve":
      return generateConnectionPoolStarve(n);
    case "future-latch-deadlock":
      return generateFutureLatchDeadlock(n);
    case "logging-appender-contention":
      return generateLoggingAppenderContention(n);
    case "busy-wait-spin":
      return generateBusyWaitSpin(n);
    case "condition-starvation":
      return generateConditionStarvation(n);
    case "lock-order-risk":
      return generateLockOrderRisk(n);
    case "finalizer-pressure":
      return generateFinalizerPressure(n);
    default:
      return generateLockContention(n);
  }
}

function generateLockContention(workers: number): string {
  const nMinus1 = workers - 1;
  return `// Auto-generated by jblock: lock-contention reproducer.
// One thread holds LOCK forever; the other ${nMinus1} block waiting to enter it.
// Capture with: jstack <pid>  (or ThreadMXBean#dumpAllThreads)
public class LockContention {
    private static final Object LOCK = new Object();

    public static void main(String[] args) {
        final int workers = ${workers};
        for (int i = 0; i < workers; i++) {
            final int id = i;
            Thread t = new Thread(() -> {
                synchronized (LOCK) {
                    System.out.println("worker-" + id + " acquired LOCK");
                    // Hold the monitor so the remaining workers stay BLOCKED.
                    while (true) {
                        try {
                            Thread.sleep(Long.MAX_VALUE);
                        } catch (InterruptedException e) {
                            Thread.currentThread().interrupt();
                            return;
                        }
                    }
                }
            }, "worker-" + i);
            t.start();
        }
    }
}
`;
}

function generateDeadlock(threads: number): string {
  return `// Auto-generated by jblock: deadlock-cycle reproducer.
// ${threads} threads and ${threads} locks form a circular wait: thread i holds lock i and
// blocks acquiring lock (i+1) % ${threads}, closing a deadlock cycle.
// Capture with: jstack <pid>  (jstack also prints "Found one Java-level deadlock").
public class DeadlockCycle {
    public static void main(String[] args) {
        final int n = ${threads};
        final Object[] locks = new Object[n];
        for (int i = 0; i < n; i++) {
            locks[i] = new Object();
        }
        for (int i = 0; i < n; i++) {
            final int id = i;
            final Object first = locks[i];
            final Object second = locks[(i + 1) % n];
            Thread t = new Thread(() -> {
                synchronized (first) {
                    System.out.println("thread-" + id + " locked " + id);
                    try {
                        Thread.sleep(200);
                    } catch (InterruptedException e) {
                        Thread.currentThread().interrupt();
                        return;
                    }
                    synchronized (second) {
                        System.out.println("thread-" + id + " locked next");
                    }
                }
            }, "deadlock-" + i);
            t.start();
        }
    }
}
`;
}

function generateThreadPoolExhaustion(workers: number): string {
  return `// Auto-generated by jblock: thread-pool-exhaustion reproducer.
// A fixed pool of ${workers} workers all enter the same monitor; one holds it while
// sleeping and the rest stay BLOCKED — no idle getTask worker remains.
// Capture with: jstack <pid>
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;

public class ThreadPoolExhaustion {
    private static final Object LOCK = new Object();

    public static void main(String[] args) throws Exception {
        final int workers = ${workers};
        final ExecutorService pool = Executors.newFixedThreadPool(workers);
        final CountDownLatch entered = new CountDownLatch(workers);
        for (int i = 0; i < workers; i++) {
            pool.submit(() -> {
                entered.countDown();
                synchronized (LOCK) {
                    try {
                        Thread.sleep(Long.MAX_VALUE);
                    } catch (InterruptedException e) {
                        Thread.currentThread().interrupt();
                    }
                }
            });
        }
        entered.await();
        // Keep the JVM alive so jstack can capture the stuck pool.
        Thread.sleep(Long.MAX_VALUE);
    }
}
`;
}

function generateSyncIoHotspot(clients: number): string {
  return `// Auto-generated by jblock: sync-io / RPC hotspot reproducer.
// A local server accepts connections but never writes; ${clients} client threads
// block forever in SocketInputStream.read — a classic synchronous I/O hotspot.
// Capture with: jstack <pid>
import java.io.InputStream;
import java.net.ServerSocket;
import java.net.Socket;
import java.util.concurrent.CountDownLatch;

public class SyncIoHotspot {
    public static void main(String[] args) throws Exception {
        final int clients = ${clients};
        final ServerSocket server = new ServerSocket(0);
        final int port = server.getLocalPort();

        Thread acceptor = new Thread(() -> {
            try {
                while (true) {
                    Socket peer = server.accept();
                    // Keep the accepted socket open without writing so clients stay blocked.
                    Thread.sleep(Long.MAX_VALUE);
                    peer.close();
                }
            } catch (Exception ignored) {
            }
        }, "io-acceptor");
        acceptor.setDaemon(true);
        acceptor.start();

        final CountDownLatch connected = new CountDownLatch(clients);
        for (int i = 0; i < clients; i++) {
            final int id = i;
            Thread t = new Thread(() -> {
                try {
                    Socket sock = new Socket("127.0.0.1", port);
                    connected.countDown();
                    InputStream in = sock.getInputStream();
                    // Block forever on a synchronous read (RPC-style stall).
                    while (in.read() >= 0) {
                        // no-op
                    }
                } catch (Exception ignored) {
                }
            }, "rpc-client-" + id);
            t.start();
        }
        connected.await();
        Thread.sleep(Long.MAX_VALUE);
    }
}
`;
}

function generateDangerousHotLock(threads: number): string {
  const waiters = Math.max(1, threads - 1);
  return `// Auto-generated by jblock: dangerous hot-lock owner reproducer.
// One owner holds LOCK while blocked in Thread.sleep; ${waiters} waiters stay BLOCKED.
// This is the "owner on blocking call" anti-pattern (feat-030).
// Capture with: jstack <pid>
import java.util.concurrent.CountDownLatch;

public class DangerousHotLock {
    private static final Object LOCK = new Object();

    public static void main(String[] args) throws Exception {
        final int waiters = ${waiters};
        final CountDownLatch ownerHolding = new CountDownLatch(1);
        final CountDownLatch waitersStarted = new CountDownLatch(waiters);

        Thread owner = new Thread(() -> {
            synchronized (LOCK) {
                ownerHolding.countDown();
                System.out.println("lock-owner holding LOCK while sleeping");
                try {
                    // Dangerous: blocking call while still holding the monitor.
                    Thread.sleep(Long.MAX_VALUE);
                } catch (InterruptedException e) {
                    Thread.currentThread().interrupt();
                }
            }
        }, "lock-owner");
        owner.start();
        ownerHolding.await();

        for (int i = 0; i < waiters; i++) {
            final int id = i;
            Thread t = new Thread(() -> {
                waitersStarted.countDown();
                synchronized (LOCK) {
                    System.out.println("waiter-" + id + " acquired LOCK");
                }
            }, "waiter-" + i);
            t.start();
        }
        waitersStarted.await();
        // Brief pause so BLOCKED waiters show up in jstack.
        Thread.sleep(300);
        Thread.sleep(Long.MAX_VALUE);
    }
}
`;
}

function generateConnectionPoolStarve(borrowers: number): string {
  const waiters = Math.max(1, borrowers - 1);
  return `// Auto-generated by jblock: connection-pool borrow blocking reproducer.
// A tiny pool of size 1 is held forever; ${waiters} callers block in getConnection()/borrowObject()
// with stack frames that mirror Hikari/DBCP-style borrow waits (feat-031).
// Capture with: jstack <pid>
import java.util.concurrent.CountDownLatch;

public class ConnectionPoolStarve {
    /** Minimal stand-in for HikariDataSource / BasicDataSource. */
    static final class HikariDataSource {
        private int available = 1;

        public synchronized Object getConnection() throws InterruptedException {
            return borrowObject();
        }

        public synchronized Object borrowObject() throws InterruptedException {
            while (available == 0) {
                wait();
            }
            available--;
            return new Object();
        }

        public synchronized void release(Object ignored) {
            available++;
            notifyAll();
        }
    }

    public static void main(String[] args) throws Exception {
        final int waiters = ${waiters};
        final HikariDataSource pool = new HikariDataSource();
        final CountDownLatch held = new CountDownLatch(1);
        final CountDownLatch waiting = new CountDownLatch(waiters);

        Thread holder = new Thread(() -> {
            try {
                Object conn = pool.getConnection();
                held.countDown();
                System.out.println("pool-holder borrowed the only connection");
                Thread.sleep(Long.MAX_VALUE);
                pool.release(conn);
            } catch (InterruptedException e) {
                Thread.currentThread().interrupt();
            }
        }, "pool-holder");
        holder.start();
        held.await();

        for (int i = 0; i < waiters; i++) {
            final int id = i;
            Thread t = new Thread(() -> {
                try {
                    waiting.countDown();
                    Object conn = pool.getConnection();
                    System.out.println("db-borrower-" + id + " got connection");
                    pool.release(conn);
                } catch (InterruptedException e) {
                    Thread.currentThread().interrupt();
                }
            }, "db-borrower-" + i);
            t.start();
        }
        waiting.await();
        Thread.sleep(400);
        Thread.sleep(Long.MAX_VALUE);
    }
}
`;
}

function generateFutureLatchDeadlock(threads: number): string {
  const futureWaiters = threads;
  return `// Auto-generated by jblock: Future/Latch wait-tree reproducer.
// ${futureWaiters} threads form a circular CompletableFuture.get() wait (logical deadlock),
// plus two threads in a CountDownLatch cross-await (feat-032).
// Capture with: jstack <pid>
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.CountDownLatch;

public class FutureLatchDeadlock {
    @SuppressWarnings("unchecked")
    public static void main(String[] args) throws Exception {
        final int futureWaiters = ${futureWaiters};
        final CompletableFuture<Void>[] futures = new CompletableFuture[futureWaiters];
        for (int i = 0; i < futureWaiters; i++) {
            futures[i] = new CompletableFuture<>();
        }
        final CountDownLatch started = new CountDownLatch(futureWaiters);

        for (int i = 0; i < futureWaiters; i++) {
            final int id = i;
            Thread t = new Thread(() -> {
                try {
                    started.countDown();
                    System.out.println("future-waiter-" + id + " waiting on future-" + ((id + 1) % futureWaiters));
                    // Logical deadlock: each waits for the next future in the ring.
                    futures[(id + 1) % futureWaiters].get();
                    futures[id].complete(null);
                } catch (Exception e) {
                    Thread.currentThread().interrupt();
                }
            }, "future-waiter-" + i);
            t.start();
        }
        started.await();

        final CountDownLatch latchA = new CountDownLatch(1);
        final CountDownLatch latchB = new CountDownLatch(1);
        Thread latch0 = new Thread(() -> {
            try {
                System.out.println("latch-waiter-0 awaiting latchB");
                latchB.await();
                latchA.countDown();
            } catch (InterruptedException e) {
                Thread.currentThread().interrupt();
            }
        }, "latch-waiter-0");
        Thread latch1 = new Thread(() -> {
            try {
                System.out.println("latch-waiter-1 awaiting latchA");
                latchA.await();
                latchB.countDown();
            } catch (InterruptedException e) {
                Thread.currentThread().interrupt();
            }
        }, "latch-waiter-1");
        latch0.start();
        latch1.start();

        Thread.sleep(400);
        Thread.sleep(Long.MAX_VALUE);
    }
}
`;
}

function generateLoggingAppenderContention(threads: number): string {
  const waiters = Math.max(1, threads - 1);
  return `// Auto-generated by jblock: logging-appender contention reproducer.
// One thread holds a synchronized OutputStreamAppender.append() (Logback/Log4j style);
// ${waiters} other loggers stay BLOCKED on the same appender lock (feat-033).
// Capture with: jstack <pid>
import java.util.concurrent.CountDownLatch;

public class LoggingAppenderContention {
    /** Minimal stand-in for Logback OutputStreamAppender / Log4j AbstractAppender. */
    static final class OutputStreamAppender {
        private final CountDownLatch entered;

        OutputStreamAppender(CountDownLatch entered) {
            this.entered = entered;
        }

        public synchronized void append(String event) {
            entered.countDown();
            try {
                // Slow append while holding the appender monitor (classic logging bottleneck).
                Thread.sleep(Long.MAX_VALUE);
            } catch (InterruptedException e) {
                Thread.currentThread().interrupt();
            }
        }

        public void doAppend(String event) {
            append(event);
        }
    }

    static final class Logger {
        private final OutputStreamAppender appender;

        Logger(CountDownLatch entered) {
            this.appender = new OutputStreamAppender(entered);
        }

        public void info(String msg) {
            appender.doAppend(msg);
        }
    }

    public static void main(String[] args) throws Exception {
        final int waiters = ${waiters};
        final CountDownLatch holding = new CountDownLatch(1);
        final CountDownLatch waiting = new CountDownLatch(waiters);
        final Logger log = new Logger(holding);

        Thread holder = new Thread(() -> {
            System.out.println("log-holder entering append()");
            log.info("slow-append");
        }, "log-holder");
        holder.start();
        holding.await();

        for (int i = 0; i < waiters; i++) {
            final int id = i;
            Thread t = new Thread(() -> {
                waiting.countDown();
                System.out.println("log-writer-" + id + " calling info()");
                log.info("blocked-append-" + id);
            }, "log-writer-" + i);
            t.start();
        }
        waiting.await();
        Thread.sleep(400);
        Thread.sleep(Long.MAX_VALUE);
    }
}
`;
}

function generateBusyWaitSpin(threads: number): string {
  return `// Auto-generated by jblock: busy-wait / CPU spin hotspot reproducer.
// ${threads} threads spin in a tight loop waiting on a flag that never flips (feat-034).
// Capture with: jstack <pid>
import java.util.concurrent.CountDownLatch;

public class BusyWaitSpin {
    static volatile boolean ready = false;
    static volatile long sink;

    /** Tight spin body kept in its own method so jstack shows a stable top frame. */
    static void spinUntilReady() {
        while (!ready) {
            sink++;
        }
    }

    public static void main(String[] args) throws Exception {
        final int workers = ${threads};
        final CountDownLatch started = new CountDownLatch(workers);

        for (int i = 0; i < workers; i++) {
            final int id = i;
            Thread t = new Thread(() -> {
                started.countDown();
                System.out.println("spin-worker-" + id + " entering busy-wait");
                spinUntilReady();
            }, "spin-worker-" + i);
            t.start();
        }
        started.await();
        Thread.sleep(400);
        // Never set ready=true — workers stay RUNNABLE in spinUntilReady().
        Thread.sleep(Long.MAX_VALUE);
    }
}
`;
}

